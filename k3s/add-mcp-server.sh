#!/usr/bin/env bash
# ============================================================================
# add-mcp-server.sh — put the gateway in front of ANOTHER MCP server on the
# k3s deployment, end to end (the pattern Demo 9 proves, generalised):
#
#   mcp-<NAME>  (Deployment + ClusterIP ONLY — a reachable-without-the-PEP
#                MCP server is ungoverned whatever the gateway says)
#   gateway-mcp-<NAME>  (same OAuth layer + secrets as gateway-mcp;
#                UPSTREAM_URL -> mcp-<NAME>; its own resource path)
#   Ingress    one more path on the SAME LE-cert'd host: /mcp-<NAME>
#   delegation JSON printed, or auto-provisioned via create-claude-delegation.sh
#
# One MCP tool call is authorized against the delegation matching the RESOURCE
# PATH it arrived on — that is what makes many servers safe on one hostname.
#
# USAGE
#   ./add-mcp-server.sh <name>                        # sensible defaults
#   IMAGE=stevef1uk/agent-gateway-mcpsrv:1.0.1 \
#   PORT=8091 \
#   TOOLS="add_customer lookup_customer list_customers find_customer delete_customer" \
#   DELETE_PATTERN=delete_customer \
#   AGENT_ID=claude-mcp-second ./add-mcp-server.sh second
#
#   Leave AGENT_ID unset to skip delegation creation (JSON printed instead).
# After it prints DONE: in claude.ai add custom connector
#   https://<host>/mcp-<name>   → Register automatically → Connect.
# ============================================================================
set -euo pipefail

NAME=${1:?"usage: add-mcp-server.sh <name>  (env: IMAGE PORT TOOLS DELETE_PATTERN AGENT_ID HOST NAMESPACE)"}
NS=${NAMESPACE:-agentgw}
HOST=${HOST:-agw.sjfisher.com}
IMAGE=${IMAGE:-stevef1uk/agent-gateway-mcpsrv:1.0.1}
GATEWAY_IMAGE=${GATEWAY_IMAGE:-stevef1uk/agent-gateway-gateway_m:1.0.36}
PORT=${PORT:-8091}
TOOL_ACTIONS=${TOOLS:-"add_customer lookup_customer list_customers find_customer delete_customer"}
DELETE_PATTERN=${DELETE_PATTERN:-delete_customer}
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GW="${SCRIPT_DIR}/mcp-${NAME}.yaml"

say()  { printf "\033[1;36m==> %s\033[0m\n" "$*"; }
ok()   { printf "    \033[0;32m✓ %s\033[0m\n" "$*"; }
die()  { printf "    \033[0;31m✗ %s\033[0m\n" "$*" >&2; exit 1; }
command -v kubectl >/dev/null || die "kubectl required"
command -v python3 >/dev/null || die "python3 required"

# ---------------------------------------------------------------- manifest
say "generating $GW (mcp-${NAME} + gateway-mcp-${NAME}, both ClusterIP)"
cat > "$GW" <<EOF
---
# MCP server '${NAME}' — generated by add-mcp-server.sh. ClusterIP ONLY.
apiVersion: apps/v1
kind: Deployment
metadata: { name: mcp-${NAME}, namespace: ${NS}, labels: { app: mcp-${NAME} } }
spec:
  replicas: 1
  selector: { matchLabels: { app: mcp-${NAME} } }
  template:
    metadata: { labels: { app: mcp-${NAME} } }
    spec:
      containers:
        - name: server
          image: ${IMAGE}
          ports: [{ containerPort: ${PORT} }]
---
apiVersion: v1
kind: Service
metadata: { name: mcp-${NAME}, namespace: ${NS} }
spec:
  type: ClusterIP
  selector: { app: mcp-${NAME} }
  ports: [{ name: mcp, port: ${PORT}, targetPort: ${PORT} }]
---
# PEP for '${NAME}' — dedicated gateway instance, resource path /mcp-${NAME}*.
apiVersion: apps/v1
kind: Deployment
metadata: { name: gateway-mcp-${NAME}, namespace: ${NS}, labels: { app: gateway-mcp-${NAME} } }
spec:
  replicas: 1
  selector: { matchLabels: { app: gateway-mcp-${NAME} } }
  template:
    metadata: { labels: { app: gateway-mcp-${NAME} } }
    spec:
      containers:
        - name: pep
          image: ${GATEWAY_IMAGE}
          ports: [{ containerPort: 8080 }]
          env:
            - { name: AUTHZ_URL, value: "http://authz:8081" }
            - { name: PERSISTENCE, value: postgres }
            - name: POSTGRES_PASSWORD
              valueFrom: { secretKeyRef: { name: agentgw-secrets, key: POSTGRES_PASSWORD } }
            - name: DATABASE_URL
              value: "postgres://agentgw:\$(POSTGRES_PASSWORD)@postgres:5432/agent_gateway?sslmode=disable"
            - { name: REDIS_URL, value: "redis://redis:6379/0" }
            - name: JWT_SECRET
              valueFrom: { secretKeyRef: { name: agentgw-secrets, key: JWT_SECRET } }
            - name: GATEWAY_ADMIN_TOKEN
              valueFrom: { secretKeyRef: { name: agentgw-secrets, key: GATEWAY_ADMIN_TOKEN } }
            - { name: OAUTH_ENABLED, value: "1" }
            - { name: OAUTH_ISSUER_URL, value: "https://${HOST}" }
            - { name: OIDC_ISSUER_URL, value: "${OIDC_ISSUER_URL:-$(kubectl -n "$NS" get deploy gateway-mcp -o jsonpath='{.spec.template.spec.containers[0].env[?(@.name=="OIDC_ISSUER_URL")].value}' 2>/dev/null || echo http://dex:5556/dex)}" }
            - { name: OIDC_CLIENT_ID, value: "agent-gateway" }
            - { name: OIDC_CONNECTOR_ID, value: "${OIDC_CONNECTOR_ID:-$(kubectl -n "$NS" get deploy gateway-mcp -o jsonpath='{.spec.template.spec.containers[0].env[?(@.name=="OIDC_CONNECTOR_ID")].value}' 2>/dev/null || echo mock)}" }
            - { name: UPSTREAM_URL, value: "http://mcp-${NAME}:${PORT}" }
            - name: APPROVAL_TELEGRAM_BOT_TOKEN
              valueFrom: { secretKeyRef: { name: agentgw-telegram, key: bot_token, optional: true } }
            - name: APPROVAL_TELEGRAM_CHAT_ID
              valueFrom: { secretKeyRef: { name: agentgw-telegram, key: chat_id, optional: true } }
            - { name: APPROVAL_CONSOLE_URL, value: "https://${HOST}" }
          volumeMounts:
            - { name: licence, mountPath: /licences/gateway.token, subPath: gateway.token, readOnly: true }
            - { name: keys, mountPath: /keys, readOnly: true }
          readinessProbe:
            httpGet: { path: /healthz, port: 8080 }
            initialDelaySeconds: 8
      volumes:
        - name: licence
          secret: { secretName: agentgw-keys, items: [{ key: license.token, path: gateway.token }] }
        - name: keys
          secret: { secretName: agentgw-keys, items: [{ key: customer_private.pem, path: customer_private.pem }] }
---
apiVersion: v1
kind: Service
metadata: { name: gateway-mcp-${NAME}, namespace: ${NS} }
spec:
  type: ClusterIP
  selector: { app: gateway-mcp-${NAME} }
  ports: [{ name: pep, port: 8080, targetPort: 8080 }]
EOF

say "applying mcp-${NAME} + gateway-mcp-${NAME}"
kubectl apply -f "$GW" >/dev/null
ok "deployments + services created"

# ------------------------------------------------- ingress path (merged)
say "merging /mcp-${NAME} path into ingress agentgw-ingress"
python3 - "$NS" "$NAME" <<'PY'
import json, subprocess, sys
ns, name = sys.argv[1], sys.argv[2]
cur = json.loads(subprocess.check_output(
    ["kubectl", "-n", ns, "get", "ingress", "agentgw-ingress", "-o", "json"]))
paths = cur["spec"]["rules"][0]["http"]["paths"]
marker = f"/mcp-{name}/"        # subpath pattern — the root /mcp prefix of the
                                # first connector stays untouched
if any(p["path"] == f"/mcp-{name}" for p in paths):
    print("      path already present; nothing to do")
    sys.exit(0)
# /mcp-<name> must sit BEFORE the catch-all "/" and before "/mcp" would not
# match it anyway (/mcp prefix only matches its own prefix), so order is fine;
# keep console "/" last.
paths.append({"path": f"/mcp-{name}", "pathType": "Prefix",
              "backend": {"service": {"name": f"gateway-mcp-{name}",
                                      "port": {"number": 8080}}}})
paths.sort(key=lambda p: p["path"] == "/")
patch = {"spec": {"rules": cur["spec"]["rules"]}}
subprocess.check_call(["kubectl", "-n", ns, "patch", "ingress", "agentgw-ingress",
                       "--type", "strategic", "-p", json.dumps(patch)])
print("      ingress updated")
PY
curl -s -o /dev/null -w "    ✓ governed check: /mcp-${NAME} → HTTP %{http_code} (401 expected — no token, no entry)\n" \
  "http://${HOST}/mcp-${NAME}" 2>/dev/null || true

# --------------------------------------------------------------- delegation
ACTIONS='["initialize","list"'; for a in $TOOL_ACTIONS; do ACTIONS="$ACTIONS,\"$a\""; done; ACTIONS="$ACTIONS]"
RULE=""
[ -n "$DELETE_PATTERN" ] && RULE='{"when":{"resource_pattern":"/mcp-${NAME}*","action_pattern":"$DELETE_PATTERN"},"require":true,"rationale":"Deleting data on ${NAME}: verify this is the right record before approving"}'

if [ -n "${AGENT_ID:-}" ] && [ -f "$(dirname "$0")/create-claude-delegation.sh" ]; then
  say "provisioning delegation via create-claude-delegation.sh"
  RESOURCE="/mcp-${NAME}*" AGENT_ID="$AGENT_ID" TOOL_ACTIONS=$(echo $TOOL_ACTIONS) \
    DELETE_PATTERN="$DELETE_PATTERN" \
    "$(dirname "$0")/create-claude-delegation.sh" --replace
else
  cat <<EOF

Delegation JSON (create via console/authz — see create-claude-delegation.sh):
  agent_id:   claude-mcp-${NAME}
  resources:  ["/mcp-${NAME}*"]
  actions:    $ACTIONS
  approval:   ${RULE:-none}
EOF
fi

cat <<EOF
DONE.
  claude.ai → Add custom connector → https://${HOST}/mcp-${NAME}
  Register automatically → sign-in → tools render — enforced + audited per tool.
  Binding note: with exactly one active delegation for your account it
  auto-binds; several → the connector shows the delegation chooser.
  Generated manifest saved at $GW (commit it: your server is now code).
EOF
